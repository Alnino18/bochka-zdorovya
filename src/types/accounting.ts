export interface ServiceOrderItem {
  id: string;
  categoryId?: string;
  serviceName: string;        // e.g. "Фитобочка, Сауна, Массаж (оздоровительный)"
  serviceNameUz?: string;      // e.g. "Fitobochka, Sauna, Massaj (sog'lomlashtiruvchi)"
  durationMinutes: number;    // 40, 60 or 0 for custom
  price: number;              // Gross price in UZS (e.g. 300000)
  timestamp?: string;         // Time of order e.g. "14:30"
}

export interface MasterEntry {
  id: string;
  name: string;        // "Иро", "Мах", "Комила"
  nameUz: string;      // "Iro", "Max", "Komila"
  clientCount: number;
  revenue: number;     // Gross revenue generated by this master
  payout: number;      // Payout share to master
  salonShare: number;  // revenue - payout
  clientSessions?: number[]; // Individual session amounts
  orders?: ServiceOrderItem[]; // Itemized list of specific massage orders
}

export interface DailyExpenses {
  cleaning: number;     // e.g. 200,000 UZS
  other: number;        // other petty expenses
  description?: string;
}

export interface BarSales {
  revenue: number;      // Total bar sales e.g. 440,000 UZS
  items?: Array<{ name: string; price: number }>;
  notes?: string;
}

export interface ClientBooking {
  id: string;
  date: string;
  phone: string;        // e.g. "97 794 14 86"
  time: string;         // e.g. "19:00"
  clientName?: string;  // e.g. "Жасмин", "2 к"
  partySize: number;
  notes?: string;
  completed?: boolean;
}

export interface DayRecord {
  id: string;           // "journal-2026-11-19"
  date: string;         // "2026-11-19"
  dateFormatted: string;// "19.11.2026"
  masters: MasterEntry[];
  expenses: DailyExpenses;
  bar: BarSales;
  bookings: ClientBooking[];
  notes?: string;
}

export interface DaySummary {
  totalClients: number;
  grossServiceRevenue: number;
  barRevenue: number;
  grossTotalRevenue: number;
  totalMasterPayouts: number;
  cleaningExpenses: number;
  otherExpenses?: number;
  facilityExpenses?: number;
  totalExpenses: number;
  netBalance: number;     // Revenue + Bar - Cleaning
  netSalonProfit: number; // Net Balance - Master Payouts
}
